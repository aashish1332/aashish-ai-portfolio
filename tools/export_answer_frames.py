"""tools/export_answer_frames.py — the trained answer sentences, as data.

WHY THIS FILE EXISTS. The runtime now decodes against a closed answer space
(`ai/engine/grammar.mjs`): a fact question may only be answered by one of the
sentences the model was TRAINED to say about a fact it was actually given,
or by `<|abstain|>`. That removes the failure the 2026-10-25 sweep measured
most often — the right sentence frame carrying the wrong fact ("His GitHub is
<email>") or a fact the turn never offered.

For that grammar to be honest it has to be built from the SAME tables the
training data is built from, not from a second copy that drifts. So this
exporter reads `ai/data/instruction.py` and writes the four tables the
runtime needs:

  frames       `_FRAMES[fact id]`             one fact, question-targeted
  kindFrames   `_COVERAGE_FRAMES[kind]`       one fact of a kind, question-agnostic
  listFrames   `_LIST_FRAMES[kind]`           a whole kind in one sentence
  separators   `_conj`                        how a list is joined, per language

plus `_COVERAGE_BY_ID` (contact.location / contact.availability, which need
their own frame because their kind is shared with a covered id).

`tools/verify_answer_frames.py`'s test (`tests/py/test_answer_frames.py`)
re-runs this and fails if the committed JSON is stale, so an edit to a frame
in `instruction.py` cannot ship a grammar that still allows the old sentence.

Run: PYTHONUTF8=1 python tools/export_answer_frames.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

if __package__ in (None, ""):
    sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from ai.data import instruction as I  # noqa: E402

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "ai" / "answers" / "answer_frames.json"

LANGS = ("en", "hi", "hinglish")

#: `_COVERAGE_FRAMES` is keyed by the FACT KIND ("certification"), while a fact
#: id is prefixed by its short name (`cert.dbms`). The runtime only has ids, so
#: the table is re-keyed by the id prefix here rather than carrying both.
KIND_BY_PREFIX = {"certification": "cert", "skill": "skill", "project": "project"}


def _personas(pair: tuple[str, str]) -> dict[str, str]:
    first, third = pair
    return {"first": first, "third": third}


def _table(frames: dict[str, dict[str, tuple[str, str]]]) -> dict:
    return {
        key: {lang: _personas(value) for lang, value in langs.items()}
        for key, langs in frames.items()
    }


def separators(lang: str) -> list[str]:
    """The two ways `_conj` joins list items, read off `_conj` itself.

    `_conj(["A", "B"], lang)` is `"A and B"`, and three items are
    `"A, B and C"` — so the last join is ` and ` and every other one is `, `.
    Deriving the word instead of copying it keeps a language added to
    `instruction.py` from silently exporting the English "and".
    """
    joined = I._conj(["A", "B"], lang)
    word = joined[len("A"):-len("B")].strip()
    return [", ", f" {word} "]


def build() -> dict:
    frames = _table(I._FRAMES)
    # Facts whose kind is shared with a covered id (`contact`) carry their own
    # frame in `_COVERAGE_BY_ID`; without this they would be unframeable and a
    # question about them would have no legal answer at all.
    for fact_id, spec in I._COVERAGE_BY_ID.items():
        frames[fact_id] = {lang: _personas(pair) for lang, pair in spec["frames"].items()}
    return {
        "generatedFrom": "ai/data/instruction.py",
        "note": "generated by tools/export_answer_frames.py — do not edit by hand",
        "languages": list(LANGS),
        "frames": frames,
        "kindFrames": {KIND_BY_PREFIX.get(kind, kind): _table({kind: table})[kind]
                       for kind, table in I._COVERAGE_FRAMES.items()},
        "listFrames": _table(I._LIST_FRAMES),
        "separators": {lang: separators(lang) for lang in LANGS},
    }


def main() -> int:
    payload = build()
    text = json.dumps(payload, ensure_ascii=False, indent=2, sort_keys=True) + "\n"
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}  {len(text):,} B")
    print(f"  frames      {len(payload['frames'])} fact ids")
    print(f"  kindFrames  {', '.join(sorted(payload['kindFrames']))}")
    print(f"  listFrames  {', '.join(sorted(payload['listFrames']))}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
